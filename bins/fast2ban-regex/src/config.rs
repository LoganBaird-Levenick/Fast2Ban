pub fn make_parser(argv0: &str) -> Parser {
    let usage = format!("{argv0} [OPTIONS] <LOG> <REGEX> [IGNOREREGEX]");
    let version = f2b_types::UPSTREAM_COMPAT_VERSION;
    let norm_version = "1.1.2.1"; // normVersion() of 1.1.2.dev1
    Parser::new(
        parser_specs(),
        argv0,
        usage.clone(),
        version,
        norm_version,
        Box::new(move |p| {
            format!(
                "Usage: {usage}\n{DOCSTRING}\nLOG:\n  string                a string representing a log line\n  filename              path to a log file (/var/log/auth.log)\n  systemd-journal       search systemd journal (systemd-python required),\n                        optionally with backend parameters, see `man jail.conf`\n                        for usage and examples (systemd-journal[journalflags=1]).\n\nREGEX:\n  string                a string representing a 'failregex'\n  filter                name of jail or filter, optionally with options (sshd[mode=aggressive])\n  filename              path to a filter file (filter.d/sshd.conf)\n\nIGNOREREGEX:\n  string                a string representing an 'ignoreregex'\n\n{}\n\nReport bugs to https://github.com/fail2ban/fail2ban/issues\n\n{COPYRIGHT}\n",
                p.format_option_help(None)
            )
        }),
    )
}
